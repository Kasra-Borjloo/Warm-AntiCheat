/**
 * Returns an inline SVG string for the requested Lucide icon.
 * @param {string} name - The Lucide icon identifier.
 * @param {object} [options] - Configuration options.
 * @param {number} [options.size=18] - Icon width and height in px.
 * @param {string} [options.className=""] - Extra CSS classes.
 * @param {string} [options.strokeWidth="2"] - SVG stroke width.
 * @returns {string} The complete SVG markup.
 */
function renderLucideIcon(name, options = {}) {
  const size = options.size || 18;
  const className = options.className ? `icon ${options.className}` : 'icon';
  const strokeWidth = options.strokeWidth || '2';
  const innerPaths = LUCIDE_ICONS[name] || LUCIDE_ICONS['info'];
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="${strokeWidth}" stroke-linecap="round" stroke-linejoin="round" class="${className}">${innerPaths}</svg>`;
}

/**
 * Replaces all DOM elements with class "lucide-icon" or attribute "data-lucide"
 * with the corresponding SVG icon.
 */
function replaceLucideIcons(root = document) {
  const elements = root.querySelectorAll('[data-lucide]');
  elements.forEach((el) => {
    const iconName = el.getAttribute('data-lucide');
    const size = parseInt(el.getAttribute('data-size') || '18', 10);
    const className = el.getAttribute('data-class') || '';
    el.innerHTML = renderLucideIcon(iconName, { size, className });
  });
}

